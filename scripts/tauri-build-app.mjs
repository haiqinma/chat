import { spawn } from "node:child_process";
import { existsSync, promises as fs } from "node:fs";
import path from "node:path";
import tauriConfig from "../src-tauri/tauri.conf.json" with { type: "json" };
import { loadBuildEnvironment } from "./build-env.mjs";

const rootDir = process.cwd();
const releaseMode = process.argv.includes("--release-updater");
const tempConfigPath = path.join(
  rootDir,
  "src-tauri",
  "tauri.release.conf.json",
);
const SEMVER_PATTERN = /^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/;

// Desktop builds embed public runtime values in the static export. Do not load
// the Web/standalone .env here; CI and command-line variables remain authoritative.
loadBuildEnvironment(rootDir);

function run(command, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: rootDir,
      env: process.env,
      stdio: "inherit",
      shell: process.platform === "win32",
      ...options,
    });

    child.on("exit", (code) => {
      if (code === 0) {
        resolve();
      } else {
        reject(
          new Error(
            `${command} ${args.join(" ")} failed with exit code ${code}`,
          ),
        );
      }
    });

    child.on("error", reject);
  });
}

function runCapture(command, args, options = {}) {
  return new Promise((resolve) => {
    let output = "";
    const child = spawn(command, args, {
      cwd: rootDir,
      env: process.env,
      stdio: ["ignore", "pipe", "pipe"],
      shell: process.platform === "win32",
      ...options,
    });

    child.stdout.on("data", (chunk) => {
      output += chunk;
    });
    child.stderr.on("data", (chunk) => {
      output += chunk;
    });
    child.on("exit", (code) => {
      resolve({ code, output });
    });
    child.on("error", (error) => {
      resolve({ code: 1, output: error.message });
    });
  });
}

function resolveArch() {
  switch (process.arch) {
    case "arm64":
      return "aarch64";
    case "x64":
      return "x64";
    default:
      return process.arch;
  }
}

function normalizeVersion(value) {
  return (
    value
      ?.trim()
      .replace(/^refs\/tags\//, "")
      .replace(/^v/i, "") || ""
  );
}

function isSemverVersion(value) {
  return SEMVER_PATTERN.test(value);
}

function resolveBuildVersion() {
  const candidates = [
    process.env.BUILD_VERSION,
    process.env.GITHUB_REF_NAME,
    process.env.npm_package_version,
    tauriConfig.version,
  ];

  for (const candidate of candidates) {
    const version = normalizeVersion(candidate);
    if (version && isSemverVersion(version)) {
      return version;
    }
  }

  throw new Error(
    "Unable to resolve a valid desktop app version. Set BUILD_VERSION to v<major>.<minor>.<patch>.",
  );
}

function resolveSigningKeySource() {
  if (process.env.TAURI_SIGNING_PRIVATE_KEY?.trim()) {
    return "TAURI_SIGNING_PRIVATE_KEY";
  }

  if (process.env.TAURI_SIGNING_PRIVATE_KEY_PATH?.trim()) {
    return "TAURI_SIGNING_PRIVATE_KEY_PATH";
  }

  return null;
}

function describeInvalidChar(value, index) {
  const char = value[index];
  return `${JSON.stringify(char)} (code ${char.charCodeAt(0)}) at offset ${index}`;
}

function validateInlineSigningKey() {
  const rawKey = process.env.TAURI_SIGNING_PRIVATE_KEY?.trim();
  if (!rawKey) {
    return;
  }

  if (/^(?:export\s+)?TAURI_SIGNING_PRIVATE_KEY\s*=/.test(rawKey)) {
    throw new Error(
      "TAURI_SIGNING_PRIVATE_KEY must contain only the raw base64 private key, not an env assignment.",
    );
  }

  const invalidChar = /[^A-Za-z0-9+/=\s]/.exec(rawKey);
  if (invalidChar) {
    throw new Error(
      `TAURI_SIGNING_PRIVATE_KEY must contain only the raw base64 private key. Found invalid character ${describeInvalidChar(rawKey, invalidChar.index)}. Do not include comments, shell syntax, public key text, or surrounding labels.`,
    );
  }

  const compactKey = rawKey.replace(/\s+/g, "");
  if (compactKey.length === 0 || compactKey.length % 4 !== 0) {
    throw new Error(
      "TAURI_SIGNING_PRIVATE_KEY is not a valid base64 string. Use the private key string generated by `npx tauri signer generate` or the contents of the generated key file.",
    );
  }

  const decodedKey = Buffer.from(compactKey, "base64").toString("utf8");
  if (
    !decodedKey.startsWith("untrusted comment:") ||
    !decodedKey.includes("secret key")
  ) {
    throw new Error(
      "TAURI_SIGNING_PRIVATE_KEY does not look like a Tauri updater private key. Check that you did not paste the public key, double-base64 the key file, or include command output text.",
    );
  }

  process.env.TAURI_SIGNING_PRIVATE_KEY = compactKey;
}

function validateReleaseSigningEnv() {
  const signingKeySource = resolveSigningKeySource();
  if (!signingKeySource) {
    throw new Error(
      "Release updater build requires TAURI_SIGNING_PRIVATE_KEY or TAURI_SIGNING_PRIVATE_KEY_PATH.",
    );
  }

  if (!process.env.TAURI_SIGNING_PRIVATE_KEY_PASSWORD?.trim()) {
    throw new Error(
      "Release updater build requires TAURI_SIGNING_PRIVATE_KEY_PASSWORD.",
    );
  }

  validateInlineSigningKey();

  return signingKeySource;
}

function readEnv(name) {
  return process.env[name]?.trim() || "";
}

const REQUIRED_DESKTOP_RUNTIME_CONFIG = [
  "ROUTER_BACKEND_URL",
  "WEBDAV_BACKEND_BASE_URL",
];

function isLoopbackHostname(hostname) {
  const normalized = hostname.trim().toLowerCase();
  return (
    normalized === "localhost" ||
    normalized === "127.0.0.1" ||
    normalized === "[::1]" ||
    normalized === "::1"
  );
}

function validatePublicDesktopUrl(name, value, { requireHttps }) {
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error(
      `${name} must be a valid absolute URL for a desktop build.`,
    );
  }

  if (!["http:", "https:"].includes(parsed.protocol)) {
    throw new Error(`${name} must use http or https.`);
  }
  if (requireHttps && parsed.protocol !== "https:") {
    throw new Error(`${name} must use HTTPS in a release desktop build.`);
  }
  if (requireHttps && isLoopbackHostname(parsed.hostname)) {
    throw new Error(
      `${name} cannot use a loopback host in a release desktop build.`,
    );
  }
}

function validateDesktopRuntimeConfig() {
  const missing = REQUIRED_DESKTOP_RUNTIME_CONFIG.filter(
    (name) => !readEnv(name),
  );
  if (missing.length > 0) {
    throw new Error(
      `Desktop build requires Router/WebDAV runtime config: ${missing.join(", ")}. ` +
        "Set these variables in .env.build or GitHub Actions Repository Variables.",
    );
  }

  if (!readEnv("CHAT_APPLICATION_UID")) {
    throw new Error(
      "Desktop build requires CHAT_APPLICATION_UID (Node applications.uid).",
    );
  }

  if (releaseMode) {
    validatePublicDesktopUrl(
      "ROUTER_BACKEND_URL",
      readEnv("ROUTER_BACKEND_URL"),
      {
        requireHttps: true,
      },
    );
    validatePublicDesktopUrl(
      "WEBDAV_BACKEND_BASE_URL",
      readEnv("WEBDAV_BACKEND_BASE_URL"),
      { requireHttps: true },
    );
    for (const name of [
      "ROUTER_PORTAL_URL",
      "ROUTER_PORTAL_TOKEN_URL",
      "ROUTER_PORTAL_RECHARGE_URL",
    ]) {
      const value = readEnv(name);
      if (value) validatePublicDesktopUrl(name, value, { requireHttps: true });
    }
  }
}

function validateDesktopAuthConfig() {
  // Static desktop builds cannot receive public config from a running Next server.
  // Validate the Node identity authorization values before producing an unusable application.
  const applicationUid = readEnv("CHAT_APPLICATION_UID");
  const required = [
    ["CENTRAL_UCAN_AUTH_BASE_URL", readEnv("CENTRAL_UCAN_AUTH_BASE_URL")],
    ["CHAT_APPLICATION_UID", applicationUid],
    ["CENTRAL_UCAN_REDIRECT_URI", readEnv("CENTRAL_UCAN_REDIRECT_URI")],
  ];
  const missing = required.filter(([, value]) => !value).map(([name]) => name);
  if (missing.length > 0) {
    throw new Error(
      `Desktop build requires Node identity login config for the automatic wallet/Passkey login flow: ${missing.join(", ")}.`,
    );
  }

  const expectedRedirectUri = "chat://localhost/central-ucan-callback.html";
  if (readEnv("CENTRAL_UCAN_REDIRECT_URI") !== expectedRedirectUri) {
    throw new Error(
      `CENTRAL_UCAN_REDIRECT_URI must be ${expectedRedirectUri} for a Tauri desktop build.`,
    );
  }

  if (releaseMode) {
    let parsedUrl;
    try {
      parsedUrl = new URL(readEnv("CENTRAL_UCAN_AUTH_BASE_URL"));
    } catch {
      throw new Error(
        "CENTRAL_UCAN_AUTH_BASE_URL must be a valid absolute URL for a release desktop build.",
      );
    }

    if (parsedUrl.protocol !== "https:") {
      throw new Error(
        "Release desktop builds require an HTTPS CENTRAL_UCAN_AUTH_BASE_URL; configure the public Node authentication service URL with a trusted certificate.",
      );
    }

    const hostname = parsedUrl.hostname;

    if (
      hostname === "localhost" ||
      hostname === "127.0.0.1" ||
      hostname === "[::1]" ||
      hostname === "::1"
    ) {
      throw new Error(
        "Release desktop builds cannot use a loopback CENTRAL_UCAN_AUTH_BASE_URL; configure the public Node authentication service URL.",
      );
    }
  }

  return {
    baseUrl: readEnv("CENTRAL_UCAN_AUTH_BASE_URL").replace(/\/+$/, ""),
    appId: applicationUid,
    redirectUri: readEnv("CENTRAL_UCAN_REDIRECT_URI"),
  };
}

async function validateDesktopAuthDeployment(config) {
  if (!releaseMode || !config) return;

  const endpoint = `${config.baseUrl}/api/v1/public/identity/authorize/validate`;
  let response;
  try {
    response = await fetch(endpoint, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        appId: config.appId,
        redirectUri: config.redirectUri,
      }),
      signal: AbortSignal.timeout(15_000),
    });
  } catch (error) {
    throw new Error(
      `Desktop authentication preflight could not reach ${endpoint}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }

  const payload = await response.json().catch(() => null);
  if (!response.ok || payload?.code !== 0) {
    throw new Error(
      `Desktop authentication preflight failed: ${payload?.message || `${response.status} ${response.statusText}`}. ` +
        "Deploy the current Node identity API and register the exact AppId/redirectUris entry before building a release.",
    );
  }

  const passkey = payload?.data?.passkey;
  if (!passkey?.enabled || !passkey?.ready) {
    throw new Error(
      `Desktop authentication preflight failed: Node Passkey is not ready (${passkey?.error || "unknown error"}).`,
    );
  }
  const issuer = payload?.data?.ucanIssuer;
  if (
    !issuer?.enabled ||
    !issuer?.ready ||
    (issuer.mode !== "issue" && issuer.mode !== "hybrid")
  ) {
    throw new Error(
      `Desktop authentication preflight failed: Node UCAN issuer is not ready for issue mode (${issuer?.error || issuer?.mode || "unknown error"}).`,
    );
  }

  console.log(
    `[Tauri] desktop authentication validated for ${payload.data.appName || config.appId}`,
  );
}

function requireMacosReleaseConfig() {
  const config = {
    appleId: readEnv("APPLE_ID"),
    applePassword: readEnv("APPLE_PASSWORD"),
    appleTeamId: readEnv("APPLE_TEAM_ID"),
    signingIdentity: readEnv("APPLE_SIGNING_IDENTITY"),
  };
  const missing = [];

  if (!config.appleId) missing.push("APPLE_ID");
  if (!config.applePassword) missing.push("APPLE_PASSWORD");
  if (!config.appleTeamId) missing.push("APPLE_TEAM_ID");
  if (!config.signingIdentity) missing.push("APPLE_SIGNING_IDENTITY");

  if (missing.length > 0) {
    throw new Error(
      `macOS release build requires Apple signing/notarization env: ${missing.join(", ")}.`,
    );
  }

  return config;
}

async function withTemporaryTauriConfig(buildVersion, callback) {
  const config = {};

  if (buildVersion !== tauriConfig.version) {
    config.version = buildVersion;
  }

  if (releaseMode) {
    config.bundle = {
      createUpdaterArtifacts: true,
      ...(process.platform === "linux" ? { targets: ["deb", "appimage"] } : {}),
    };
  }

  if (Object.keys(config).length === 0) {
    await callback(undefined);
    return;
  }

  await fs.writeFile(tempConfigPath, JSON.stringify(config, null, 2));

  try {
    await callback(tempConfigPath);
  } finally {
    try {
      await fs.unlink(tempConfigPath);
    } catch {}
  }
}

async function buildTauri(configPath) {
  const args = ["tauri", "build"];

  if (process.platform === "darwin") {
    args.push("--bundles", "app");
  }

  if (configPath) {
    args.push("--config", configPath);
  }

  await run("npx", args);
}

async function ensureMacosAppSignature(appPath) {
  if (releaseMode) {
    const config = requireMacosReleaseConfig();

    await run("codesign", [
      "--force",
      "--deep",
      "--options",
      "runtime",
      "--sign",
      config.signingIdentity,
      appPath,
    ]);

    const developerIdVerify = await runCapture("codesign", [
      "--verify",
      "--deep",
      "--strict",
      "--verbose=2",
      appPath,
    ]);

    if (developerIdVerify.code !== 0) {
      throw new Error(
        `macOS Developer ID app signature verification failed:\n${developerIdVerify.output.trim()}`,
      );
    }

    return;
  }

  const verify = await runCapture("codesign", [
    "--verify",
    "--deep",
    "--strict",
    "--verbose=2",
    appPath,
  ]);

  if (verify.code === 0) {
    return;
  }

  console.warn(
    "[Tauri] macOS app signature incomplete; applying ad-hoc signature",
  );
  await run("codesign", ["--force", "--deep", "--sign", "-", appPath]);

  const adHocVerify = await runCapture("codesign", [
    "--verify",
    "--deep",
    "--strict",
    "--verbose=2",
    appPath,
  ]);

  if (adHocVerify.code !== 0) {
    throw new Error(
      `macOS ad-hoc signature verification failed:\n${adHocVerify.output.trim()}`,
    );
  }
}

async function rebuildMacosUpdaterArchive(macosDir, appName) {
  if (!releaseMode) {
    return;
  }

  const updaterBundleName = `${appName}.tar.gz`;
  const updaterBundlePath = path.join(macosDir, updaterBundleName);
  const updaterSignaturePath = `${updaterBundlePath}.sig`;

  if (existsSync(updaterBundlePath)) {
    await fs.unlink(updaterBundlePath);
  }

  if (existsSync(updaterSignaturePath)) {
    await fs.unlink(updaterSignaturePath);
  }

  await run("tar", ["-czf", updaterBundleName, appName], { cwd: macosDir });
  await run("npx", ["tauri", "signer", "sign", updaterBundlePath]);
  await fs.access(updaterBundlePath);
  await fs.access(updaterSignaturePath);
}

async function verifyMacosDmg(dmgPath) {
  const verify = await runCapture("hdiutil", ["verify", dmgPath]);
  if (verify.code !== 0) {
    throw new Error(`DMG verification failed:\n${verify.output.trim()}`);
  }
}

async function signAndNotarizeDmg(dmgPath) {
  if (!releaseMode) {
    await verifyMacosDmg(dmgPath);
    return;
  }

  const config = requireMacosReleaseConfig();

  await run("codesign", ["--force", "--sign", config.signingIdentity, dmgPath]);

  const signature = await runCapture("codesign", [
    "--verify",
    "--verbose=2",
    dmgPath,
  ]);

  if (signature.code !== 0) {
    throw new Error(
      `DMG signature verification failed:\n${signature.output.trim()}`,
    );
  }

  await run("xcrun", [
    "notarytool",
    "submit",
    dmgPath,
    "--apple-id",
    config.appleId,
    "--password",
    config.applePassword,
    "--team-id",
    config.appleTeamId,
    "--wait",
  ]);
  await run("xcrun", ["stapler", "staple", dmgPath]);

  const assess = await runCapture("spctl", [
    "--assess",
    "--type",
    "open",
    "--context",
    "context:primary-signature",
    "--verbose=4",
    dmgPath,
  ]);

  if (assess.code !== 0) {
    throw new Error(
      `DMG Gatekeeper assessment failed:\n${assess.output.trim()}`,
    );
  }
}

async function buildDmg(buildVersion) {
  const productName = tauriConfig.productName;
  const version = buildVersion;
  const arch = resolveArch();
  const macosDir = path.join(
    rootDir,
    "src-tauri",
    "target",
    "release",
    "bundle",
    "macos",
  );
  const dmgDir = path.join(
    rootDir,
    "src-tauri",
    "target",
    "release",
    "bundle",
    "dmg",
  );
  const bundleScript = path.join(dmgDir, "bundle_dmg.sh");
  const iconPath = path.join(dmgDir, "icon.icns");
  const appName = `${productName}.app`;
  const appPath = path.join(macosDir, appName);
  const dmgName = `${productName}_${version}_${arch}.dmg`;
  const dmgPath = path.join(macosDir, dmgName);
  const tempDmgSuffix = `.${dmgName}`;

  for (const entry of await fs.readdir(macosDir)) {
    if (entry.startsWith("rw.") && entry.endsWith(tempDmgSuffix)) {
      await fs.unlink(path.join(macosDir, entry));
    }
  }

  if (existsSync(dmgPath)) {
    await fs.unlink(dmgPath);
  }

  if (!existsSync(appPath)) {
    throw new Error(`Missing macOS app bundle: ${appPath}`);
  }

  await ensureMacosAppSignature(appPath);
  await rebuildMacosUpdaterArchive(macosDir, appName);

  if (!existsSync(bundleScript)) {
    const stagingDir = path.join(
      macosDir,
      `.dmg-stage-${productName}-${version}-${arch}`,
    );
    await fs.rm(stagingDir, { recursive: true, force: true });
    await fs.mkdir(stagingDir, { recursive: true });

    try {
      await run("ditto", [appPath, path.join(stagingDir, appName)]);
      await fs.symlink("/Applications", path.join(stagingDir, "Applications"));
      await run("hdiutil", [
        "create",
        "-volname",
        productName,
        "-srcfolder",
        stagingDir,
        "-ov",
        "-format",
        "UDZO",
        dmgPath,
      ]);
    } finally {
      await fs.rm(stagingDir, { recursive: true, force: true });
    }
  } else {
    await run(
      bundleScript,
      [
        "--skip-jenkins",
        "--volname",
        productName,
        "--icon",
        appName,
        "180",
        "170",
        "--app-drop-link",
        "480",
        "170",
        "--window-size",
        "660",
        "400",
        "--hide-extension",
        appName,
        "--volicon",
        iconPath,
        dmgName,
        appName,
      ],
      { cwd: macosDir },
    );

    for (const entry of await fs.readdir(macosDir)) {
      if (entry.startsWith("rw.") && entry.endsWith(tempDmgSuffix)) {
        await fs.unlink(path.join(macosDir, entry));
      }
    }
  }

  await signAndNotarizeDmg(dmgPath);
}

const releaseSigningKeySource = releaseMode
  ? validateReleaseSigningEnv()
  : null;
const macosReleaseConfig =
  releaseMode && process.platform === "darwin"
    ? requireMacosReleaseConfig()
    : null;

const desktopAuthConfig = validateDesktopAuthConfig();
validateDesktopRuntimeConfig();
await validateDesktopAuthDeployment(desktopAuthConfig);
await run("npm", ["run", "skill"]);

const buildVersion = resolveBuildVersion();
process.env.BUILD_VERSION = buildVersion;
console.log(`[Tauri] desktop app version ${buildVersion}`);

if (releaseMode) {
  console.log(
    `[Tauri] updater release build enabled via ${releaseSigningKeySource}`,
  );

  if (macosReleaseConfig) {
    console.log(
      `[Tauri] macOS release signing identity ${macosReleaseConfig.signingIdentity}`,
    );
  }

  await withTemporaryTauriConfig(buildVersion, async (configPath) => {
    await buildTauri(configPath);
  });
} else {
  await withTemporaryTauriConfig(buildVersion, async (configPath) => {
    await buildTauri(configPath);
  });
}

if (process.platform === "darwin") {
  await buildDmg(buildVersion);
}
